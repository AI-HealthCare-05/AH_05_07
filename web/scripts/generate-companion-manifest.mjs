import { fileURLToPath } from "node:url";
import path from "node:path";
import fs from "node:fs";

const scriptRoot = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(scriptRoot, "..");
const repoRoot = path.resolve(webRoot, "..");
const evidencePath = path.join(repoRoot, "docs", "evidence", "companion-r2-v1.json");
const outputPath = path.join(webRoot, "src", "ui", "companionAssets.generated.ts");
const approvedRuntimeOrigin = "https://sk7-companion.gkrry.com";
const approvedBucket = "sk7-assets-prod";
const approvedPrefix = "companion/v1/";
const expectedSpecies = ["bear", "rabbit", "cat", "dog", "red_panda", "otter", "capybara", "hedgehog", "penguin", "fox", "squirrel"];
const expectedVariants = ["standard", "lite"];

export function buildGeneratedSource(evidence) {
  if (evidence.schema_version !== 2) throw new Error("companion evidence schema must be version 2");
  if (evidence.status !== "published_and_verified") throw new Error("companion evidence is not published_and_verified");
  if (evidence.asset_file_count !== 22 || evidence.standard_count !== 11 || evidence.lite_count !== 11 || evidence.seal_count !== 0) {
    throw new Error("companion evidence asset counts do not match the approved contract");
  }

  const runtimeDelivery = evidence.runtime_delivery;
  const verification = runtimeDelivery?.verification;
  if (
    !runtimeDelivery
    || runtimeDelivery.custom_domain !== approvedRuntimeOrigin
    || runtimeDelivery.bucket !== approvedBucket
    || runtimeDelivery.prefix !== approvedPrefix
    || runtimeDelivery.source_objects_unchanged !== true
    || runtimeDelivery.object_count !== 22
    || verification?.result !== "pass"
    || verification.objects_checked !== 22
    || verification.http_status !== 200
    || verification.content_type !== evidence.mime
    || verification.bytes_match !== true
    || verification.sha256_match !== true
    || verification.cache_control !== evidence.cache_control
    || verification.redirects !== "none"
    || verification.cf_mitigated_absent !== true
    || verification.node_fetch_origin !== "http://127.0.0.1:4173"
    || verification.node_fetch_cors !== "pass"
    || verification.chromium_fetch !== "pass"
  ) {
    throw new Error("companion runtime delivery evidence is missing or not verified");
  }

  const objects = evidence.objects ?? [];
  if (objects.length !== 22 || objects.some((asset) => (
    !expectedSpecies.includes(asset.species)
    || !expectedVariants.includes(asset.variant)
    || typeof asset.r2_object_key !== "string"
    || !asset.r2_object_key.startsWith(approvedPrefix)
    || asset.r2_object_key.startsWith("/")
    || asset.r2_object_key.includes("//")
  ))) {
    throw new Error("companion evidence contains an unapproved species or variant");
  }
  const byKey = new Map(objects.map((asset) => [`${asset.species}:${asset.variant}`, asset]));
  if (byKey.size !== 22 || expectedSpecies.some((species) => expectedVariants.some((variant) => !byKey.has(`${species}:${variant}`)))) {
    throw new Error("companion evidence does not contain exactly one standard and lite asset per species");
  }

  const manifest = Object.fromEntries(expectedSpecies.map((species) => [species, Object.fromEntries(expectedVariants.map((variant) => {
    const asset = byKey.get(`${species}:${variant}`);
    return [variant, {
      assetId: asset.asset_id,
      species: asset.species,
      version: asset.version,
      variant: asset.variant,
      url: `${runtimeDelivery.custom_domain.replace(/\/+$/, "")}/${asset.r2_object_key.replace(/^\/+/, "")}`,
      bytes: asset.bytes,
      sha256: asset.sha256,
    }];
  }))]));

  const evidenceMetadata = JSON.stringify({
    deliveryVersion: evidence.delivery_version,
    inventorySha256: evidence.inventory.sha256,
    assetCount: evidence.asset_file_count,
    totalBytes: evidence.total_bytes,
    customDomain: evidence.custom_domain,
    runtimeDeliveryDomain: runtimeDelivery.custom_domain,
  }, null, 2);
  return [
    "// Generated by scripts/generate-companion-manifest.mjs from docs/evidence/companion-r2-v1.json.",
    "// Do not edit by hand; run npm run prebuild after changing the evidence.",
    'import type { CompanionSpecies, CompanionVariant } from "./companion";',
    "",
    "export type CompanionAsset = Readonly<{",
    "  assetId: string;",
    "  species: CompanionSpecies;",
    "  version: string;",
    "  variant: CompanionVariant;",
    "  url: string;",
    "  bytes: number;",
    "  sha256: string;",
    "}>;",
    "",
    `export const companionAssetManifest = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<CompanionSpecies, Record<CompanionVariant, CompanionAsset>>;`,
    "",
    `export const companionManifestEvidence = ${evidenceMetadata} as const;`,
    "",
    "export function getCompanionAsset(species: CompanionSpecies, variant: CompanionVariant): CompanionAsset {",
    "  return companionAssetManifest[species][variant];",
    "}",
    "",
  ].join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const evidence = JSON.parse(fs.readFileSync(evidencePath, "utf8"));
  fs.writeFileSync(outputPath, buildGeneratedSource(evidence));
}
